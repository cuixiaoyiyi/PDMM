package rev8;

import java.io.File;
import java.io.FileWriter;
import java.io.PrintWriter;
import java.util.ArrayList;
import java.util.Collections;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

import jymbolic.android.config.AndroidSootConfig;
import jymbolic.android.config.AndrolicConfigurationManager;
import jymbolic.execution.SymbolicEngine;
import rev.common.Kinds;
import rev.common.LiveSetTracker;
import soot.Scene;
import soot.SootClass;
import soot.SootMethod;

/**
 * Runs Androlic (DMMPP's downstream symbolic engine, unchanged) on every
 * component of an app with dummy mains generated by Gen8 under one
 * configuration. Everything except the dummy main is identical between
 * configurations, so differences are attributable to the generator.
 *
 * Usage: java rev8.Androlic8 <fixed|hsm> <perarg|pertype|rules> <configFile> <outCsv> <label> <rep>
 * Appends one row per component to <outCsv>.components.csv and one row per run to <outCsv>:
 *   label,lifecycle,params,rep,components,generated,failed,spliced,total_paths,time_s,live_any_mb,live_major_mb,major_gcs,formals,status
 */
public class Androlic8 {

    public static void main(String[] args) throws Exception {
        Gen8.Lifecycle lc = args[0].equals("hsm") ? Gen8.Lifecycle.HSM : Gen8.Lifecycle.DMMPP_FIXED;
        Gen8.Params pm = Gen8.Params.valueOf(args[1].toUpperCase());
        String configFile = args[2];
        String outCsv = args[3];
        String label = args[4];
        String rep = args[5];

        LiveSetTracker live = LiveSetTracker.start();
        long t0 = System.nanoTime();
        String status = "OK";
        int comps = 0, generated = 0, failed = 0, spliced = 0, formals = 0;
        long totalPaths = 0;
        List<String> compRows = new ArrayList<String>();

        try {
            AndrolicConfigurationManager.init(new String[] { "-configureFile", configFile });
            new AndroidSootConfig().sootInitialization();
            // DMMPP's callback and layout parsers need the APK path in its config class
            SootSetup.configureDmmpp(configFile);

            List<SootClass> classes = new ArrayList<SootClass>(Scene.v().getApplicationClasses());
            Collections.sort(classes, new Comparator<SootClass>() {
                @Override public int compare(SootClass a, SootClass b) { return a.getName().compareTo(b.getName()); }
            });
            Map<SootClass, FragmentHosts.Info> hosts = new LinkedHashMap<SootClass, FragmentHosts.Info>();
            Set<SootClass> hostedFragments = new LinkedHashSet<SootClass>();
            for (SootClass c : classes) {
                if (c.isPhantom() || c.isAbstract() || !Kinds.isActivity(c)) continue;
                FragmentHosts.Info info = FragmentHosts.scan(c);
                hosts.put(c, info);
                if (lc == Gen8.Lifecycle.HSM) hostedFragments.addAll(info.fragments);
            }

            for (SootClass c : classes) {
                String kind = Kinds.kindOf(c);
                if ("CB".equals(kind) || "APP".equals(kind) || c.isPhantom() || c.isAbstract()) continue;
                comps++;
                if ("FRAG".equals(kind) && hostedFragments.contains(c)) {
                    spliced++;
                    compRows.add(csv(label, args[0], args[1], rep, c.getName(), kind, "SPLICED", "0", "0", "0.00"));
                    continue;
                }
                SootMethod dmm = null;
                int nf = 0;
                try {
                    Gen8.Result r;
                    if ("ACT".equals(kind)) r = Gen8.activity(c, hosts.get(c), lc, pm);
                    else if ("FRAG".equals(kind)) r = Gen8.fragment(c, pm);
                    else if ("SRV".equals(kind)) r = Gen8.service(c, pm);
                    else if ("RCV".equals(kind)) r = Gen8.receiver(c, pm);
                    else r = Gen8.provider(c, pm);
                    dmm = r.dmm;
                    nf = r.formals;
                    formals += nf;
                    generated++;
                } catch (Throwable t) {
                    failed++;
                    compRows.add(csv(label, args[0], args[1], rep, c.getName(), kind, "GENFAIL:" + t.getClass().getSimpleName(), "0", "0", "0.00"));
                    continue;
                }
                long c0 = System.nanoTime();
                String st = "OK";
                int paths = 0;
                try {
                    paths = new SymbolicEngine(c).solve(dmm);
                    totalPaths += paths;
                } catch (Throwable t) {
                    st = "SOLVEFAIL:" + t.getClass().getSimpleName();
                }
                compRows.add(csv(label, args[0], args[1], rep, c.getName(), kind, st, String.valueOf(nf), String.valueOf(paths),
                        String.format("%.2f", (System.nanoTime() - c0) / 1e9)));
            }
        } catch (Throwable t) {
            status = "ERR:" + t.getClass().getSimpleName();
            t.printStackTrace();
        }
        double secs = (System.nanoTime() - t0) / 1e9;
        long[] lv = live.finish();

        synchronized (Androlic8.class) {
            boolean header = !new File(outCsv).exists();
            try (PrintWriter pw = new PrintWriter(new FileWriter(outCsv, true))) {
                if (header) pw.println("label,lifecycle,params,rep,components,generated,failed,spliced,total_paths,time_s,live_any_mb,live_major_mb,major_gcs,formals,status");
                pw.println(csv(label, args[0], args[1], rep, String.valueOf(comps), String.valueOf(generated), String.valueOf(failed),
                        String.valueOf(spliced), String.valueOf(totalPaths), String.format("%.2f", secs), String.valueOf(lv[0]),
                        String.valueOf(lv[1]), String.valueOf(lv[2]), String.valueOf(formals), status));
            }
            String compCsv = outCsv.replace(".csv", "") + ".components.csv";
            boolean h2 = !new File(compCsv).exists();
            try (PrintWriter pw = new PrintWriter(new FileWriter(compCsv, true))) {
                if (h2) pw.println("label,lifecycle,params,rep,component,kind,status,formals,paths,time_s");
                for (String r : compRows) pw.println(r);
            }
        }
        System.out.printf("[ANDROLIC] %s %s/%s rep=%s comps=%d gen=%d spliced=%d paths=%d time=%.1fs live=%d/%dMB formals=%d %s%n",
                label, args[0], args[1], rep, comps, generated, spliced, totalPaths, secs, lv[0], lv[1], formals, status);
        System.exit(0);
    }

    static String csv(String... f) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < f.length; i++) {
            if (i > 0) sb.append(',');
            String v = f[i] == null ? "" : f[i];
            if (v.indexOf(',') >= 0 || v.indexOf('"') >= 0) v = '"' + v.replace("\"", "\"\"") + '"';
            sb.append(v);
        }
        return sb.toString();
    }
}
